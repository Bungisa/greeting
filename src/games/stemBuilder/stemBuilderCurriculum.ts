// Helper to build 4 difficulty variations for non-bridge interactive STEM tasks
function makeInteractiveTaskSet(
  base: Omit<
    InteractiveTaskStep,
    'id' | 'difficulty' | 'numericalQuestion' | 'expectedAnswer' | 'numericTolerance'
  >,
  variants: Record<
    StemDifficulty,
    {
      numericalQuestion: string;
      expectedAnswer: number | string;
      numericTolerance?: number;
      targetParameterValue?: number;
    }
  >
): Record<StemDifficulty, InteractiveTaskStep> {
  const diffs: StemDifficulty[] = ['Easy', 'Medium', 'Hard', 'Exam Challenge'];
  const out = {} as Record<StemDifficulty, InteractiveTaskStep>;
  for (const d of diffs) {
    out[d] = {
      ...base,
      id: `${base.title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${d.toLowerCase()}`,
      difficulty: d,
      numericalQuestion: variants[d].numericalQuestion,
      expectedAnswer: variants[d].expectedAnswer,
      numericTolerance: variants[d].numericTolerance ?? 0.2,
      targetParameterValue: variants[d].targetParameterValue ?? base.targetParameterValue,
    };
  }
  return out;
}

