// ==================== STORAGE & PROGRESS PERSISTENCE (ISOLATED NAMESPACE) ====================
const STEM_BUILDER_STORAGE_KEY = 'elimika_stem_builder_progress_v1';

export const DEFAULT_STEM_BUILDER_PROGRESS: StemBuilderProgress = {
  xp: 0,
  coins: 100,
  unlockedBadges: [],
  completedTopicIds: [],
  completedMissionIds: [],
  bestScoresByTopic: {},
  bestStarsByTopic: {},
  recentSessions: [],
  tutorialSeen: false,
  graphicsQuality: 'Medium',
  untimedPracticeMode: false,
};

export function loadStemBuilderProgress(): StemBuilderProgress {
  if (typeof window === 'undefined') return DEFAULT_STEM_BUILDER_PROGRESS;
  try {
    const raw = localStorage.getItem(STEM_BUILDER_STORAGE_KEY);
    if (!raw) return DEFAULT_STEM_BUILDER_PROGRESS;
    const parsed = JSON.parse(raw) as Partial<StemBuilderProgress>;
    return {
      xp: typeof parsed.xp === 'number' && parsed.xp >= 0 ? parsed.xp : 0,
      coins: typeof parsed.coins === 'number' && parsed.coins >= 0 ? parsed.coins : 100,
      unlockedBadges: Array.isArray(parsed.unlockedBadges) ? parsed.unlockedBadges : [],
      completedTopicIds: Array.isArray(parsed.completedTopicIds) ? parsed.completedTopicIds : [],
      completedMissionIds: Array.isArray(parsed.completedMissionIds) ? parsed.completedMissionIds : [],
      bestScoresByTopic:
        parsed.bestScoresByTopic && typeof parsed.bestScoresByTopic === 'object'
          ? parsed.bestScoresByTopic
          : {},
      bestStarsByTopic:
        parsed.bestStarsByTopic && typeof parsed.bestStarsByTopic === 'object'
          ? parsed.bestStarsByTopic
          : {},
      recentSessions: Array.isArray(parsed.recentSessions) ? parsed.recentSessions.slice(0, 30) : [],
      tutorialSeen: Boolean(parsed.tutorialSeen),
      graphicsQuality:
        parsed.graphicsQuality === 'Low' ||
        parsed.graphicsQuality === 'Medium' ||
        parsed.graphicsQuality === 'High'
          ? parsed.graphicsQuality
          : 'Medium',
      untimedPracticeMode: Boolean(parsed.untimedPracticeMode),
    };
  } catch {
    return DEFAULT_STEM_BUILDER_PROGRESS;
  }
}

export function saveStemBuilderProgress(progress: StemBuilderProgress): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STEM_BUILDER_STORAGE_KEY, JSON.stringify(progress));
  } catch {
    // ignore storage quota errors
  }
}

export function recordStemActivityCompletion(
  current: StemBuilderProgress,
  params: {
    topic: CurriculumTopicRecord;
    difficulty: StemDifficulty;
    activityType: StemActivityType;
    score: number;
    stars: 0 | 1 | 2 | 3;
    passed: boolean;
  }
): {
  updated: StemBuilderProgress;
  earnedXp: number;
  earnedCoins: number;
  newlyUnlockedBadge: string | null;
} {
  const { topic, difficulty, activityType, score, stars, passed } = params;
  const diffMultiplier =
    difficulty === 'Exam Challenge' ? 1.4 : difficulty === 'Hard' ? 1.25 : difficulty === 'Medium' ? 1.1 : 1.0;

  const earnedXp = passed
    ? Math.round(topic.rewards.xp * (score / 100) * diffMultiplier)
    : Math.round(topic.rewards.xp * 0.25);
  const earnedCoins = passed
    ? Math.round(topic.rewards.coins * (Math.max(1, stars) / 3) * diffMultiplier)
    : 10;

  const badgeLabel = topic.rewards.badgeLabel || null;
  const newlyUnlockedBadge =
    passed && badgeLabel && !current.unlockedBadges.includes(badgeLabel) ? badgeLabel : null;

  const prevBestScore = current.bestScoresByTopic[topic.id] || 0;
  const prevBestStars = current.bestStarsByTopic[topic.id] || 0;

  const session: StemSessionRecord = {
    id: `sess-${Date.now()}`,
    timestamp: new Date().toISOString().split('T')[0],
    subject: topic.subject,
    formLevel: topic.formLevel,
    topicId: topic.id,
    topicName: topic.topic,
    difficulty,
    activityType,
    score,
    stars,
    passed,
  };

  const updated: StemBuilderProgress = {
    ...current,
    xp: current.xp + earnedXp,
    coins: current.coins + earnedCoins,
    unlockedBadges: newlyUnlockedBadge
      ? [...current.unlockedBadges, newlyUnlockedBadge]
      : current.unlockedBadges,
    completedTopicIds:
      passed && !current.completedTopicIds.includes(topic.id)
        ? [...current.completedTopicIds, topic.id]
        : current.completedTopicIds,
    completedMissionIds:
      passed && topic.bridgeMissionId && !current.completedMissionIds.includes(topic.bridgeMissionId)
        ? [...current.completedMissionIds, topic.bridgeMissionId]
        : current.completedMissionIds,
    bestScoresByTopic: {
      ...current.bestScoresByTopic,
      [topic.id]: Math.max(prevBestScore, score),
    },
    bestStarsByTopic: {
      ...current.bestStarsByTopic,
      [topic.id]: Math.max(prevBestStars, stars),
    },
    recentSessions: [session, ...current.recentSessions].slice(0, 25),
  };

  saveStemBuilderProgress(updated);
  return { updated, earnedXp, earnedCoins, newlyUnlockedBadge };
}
