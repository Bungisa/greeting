function buildMathCheckpoints(
  easyQ: string,
  easyAns: number,
  medQ: string,
  medAns: number,
  hardQ: string,
  hardAns: number,
  examQ: string,
  examAns: number,
  unit: string,
  hint: string,
  solution: string
) {
  return {
    Easy: {
      question: easyQ,
      unit,
      expectedValue: easyAns,
      tolerance: 0.25,
      formulaHint: hint,
      workedSolution: solution,
    },
    Medium: {
      question: medQ,
      unit,
      expectedValue: medAns,
      tolerance: 0.2,
      formulaHint: hint,
      workedSolution: solution,
    },
    Hard: {
      question: hardQ,
      unit,
      expectedValue: hardAns,
      tolerance: 0.15,
      formulaHint: hint,
      workedSolution: solution,
    },
    'Exam Challenge': {
      question: examQ,
      unit,
      expectedValue: examAns,
      tolerance: 0.1,
      formulaHint: hint,
      workedSolution: solution,
    },
  };
}

